printf '\nABI verification — turns remote runtime failures into local build failures\n'
# Rationale: these four checks are the difference between "fails on the build host
# with an explanation" and "fails on the device with 'version GLIBC_2.38 not
# found'". The original design had NO verification of any kind.
# ─────────────────────────────────────────────────────────────────────────────

CXX=""
for c in g++ clang++ c++; do have "$c" && { CXX=$c; break; }; done

# The reader this group will use. Resolved into a variable instead of spelling `readelf`
# in the body: the guard has always accepted llvm-readelf, but three lines inside called
# bare `readelf`, so on a host that has only llvm-readelf (a Linux box with LLVM and no
# binutils) the group ran and those three lines silently produced empty values.
RE=""
for r in readelf llvm-readelf; do have "$r" && { RE=$r; break; }; done

# An ELF host, not merely a host with a readelf. A Mac with Homebrew's keg-only llvm on
# PATH satisfies `have llvm-readelf` and then compiles Mach-O, so `readelf -l` printed
# nothing, the fixture's TARGET_DYNAMIC_LINKER came out empty and the two
# -Wl,--disable-new-dtags links failed outright — three tests reporting verifier defects
# that were really a host mismatch. The Mach-O equivalents are their own group, below.
if [[ -n $CXX && $HOST_BINFMT == elf && -n $RE ]]; then
  mkdir -p "$TMP/abi"
  cat > "$TMP/abi/x.cpp" <<'EOF'
#include <string>
#include <cstdio>
int main(){ std::string s="x"; std::printf("%s\n", s.c_str()); return 0; }
EOF
  $CXX -O0 "$TMP/abi/x.cpp" -o "$TMP/abi/app" >/dev/null 2>&1
  hostarch=$(uname -m)
  hostinterp=$("$RE" -l "$TMP/abi/app" 2>/dev/null | sed -n 's/.*interpreter: \([^]]*\)\].*/\1/p' | head -1)
  hostglibc=$(getconf GNU_LIBC_VERSION 2>/dev/null | awk '{print $2}')

  # A description that matches this host exactly -> must PASS.
  cat > "$TMP/abi/match.conf" <<EOF
TARGET_NAME=match
TARGET_TRIPLE=$(uname -m)-linux-gnu
TARGET_ARCH=$hostarch
TARGET_LIBC=glibc
TARGET_LIBC_VERSION=${hostglibc:-2.99}
TARGET_DYNAMIC_LINKER=$hostinterp
EOF
  it "a correct binary PASSES verification"
  expect_ok "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/match.conf"

  it "a target with an OLDER glibc FAILS (the catch-it-early check)"
  sed 's/^TARGET_LIBC_VERSION=.*/TARGET_LIBC_VERSION=2.5/' "$TMP/abi/match.conf" > "$TMP/abi/old.conf"
  expect_out 'libc too new' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/old.conf"

  it "an architecture mismatch FAILS ('Exec format error' caught on the host)"
  # The "other" architecture is picked so its ELF-machine string DIFFERS from the host's,
  # which is the thing the verifier actually compares. Choosing aarch64 unless the host
  # said aarch64 was not enough: `uname -m` reports arm64 on Darwin and aarch64 on Linux
  # for the same chip, and the table maps BOTH to 'AArch64' — so on an arm64 host the
  # "mismatch" fixture named a different string for the same machine and the test failed
  # for being right. s390x shares its machine string with nothing.
  otherarch=s390x; [[ $hostarch == s390x ]] && otherarch=x86_64
  sed "s/^TARGET_ARCH=.*/TARGET_ARCH=$otherarch/" "$TMP/abi/match.conf" > "$TMP/abi/arch.conf"
  expect_out 'architecture mismatch' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/arch.conf"

  it "a wrong ELF interpreter FAILS (the 'No such file' mystery, caught early)"
  sed 's|^TARGET_DYNAMIC_LINKER=.*|TARGET_DYNAMIC_LINKER=/lib/ld-nonsense.so.9|' "$TMP/abi/match.conf" > "$TMP/abi/interp.conf"
  expect_out 'interpreter mismatch' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/interp.conf"

    it "an EMPTY RPATH entry is a FAILURE (it means 'search the cwd')"
  # Regression: the RPATH parser ran sed '/^$/d' BEFORE checking, so it deleted the
  # empty entry it was supposed to find and reported rpath '[:$ORIGIN]' as ok.
  $CXX -O0 "$TMP/abi/x.cpp" -Wl,-rpath,':$ORIGIN' -Wl,--disable-new-dtags -o "$TMP/abi/emptyrp" >/dev/null 2>&1
  expect_out 'EMPTY entry' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/emptyrp" --target-conf "$TMP/abi/match.conf"

  it "a correct \$ORIGIN RPATH does NOT trigger the empty-entry check"
  # Guards the obvious wrong fix: wrapping the value in colons before matching turns
  # every single-entry RPATH into ':foo:' and fails every correct binary.
  $CXX -O0 "$TMP/abi/x.cpp" -Wl,-rpath,'$ORIGIN' -Wl,--disable-new-dtags -o "$TMP/abi/goodrp" >/dev/null 2>&1
  expect_ok "$ROOT/tools/verify-artifact.sh" "$TMP/abi/goodrp" --target-conf "$TMP/abi/match.conf"

  it "a known-but-different TARGET_ARCH FAILS (arch table is shared and populated)"
  # loongarch64 IS in tools/arch-table.sh, so this must be a hard architecture
  # mismatch, not a skip.
  sed 's/^TARGET_ARCH=.*/TARGET_ARCH=loongarch64/' "$TMP/abi/match.conf" > "$TMP/abi/loong.conf"
  expect_out 'architecture mismatch' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/loong.conf"

  it "BOTH C++ ABI namespaces are checked, not just GLIBCXX_"
  # libstdc++ versions its symbols in two independent namespaces and a binary can exceed
  # either. This checked only GLIBCXX_, so an artifact needing a CXXABI_ tag the target
  # lacks verified clean and failed on the device with "version `CXXABI_1.3.15' not found".
  # Measured on a real device: it provides GLIBCXX_3.4.32 and CXXABI_1.3.14.
  sed 's/^TARGET_CXXABI_MAX=.*/TARGET_CXXABI_MAX=GLIBCXX_9.9.9 CXXABI_1.3.0/' \
      "$TMP/abi/match.conf" > "$TMP/abi/cxxabi.conf"
  if grep -q 'TARGET_CXXABI_MAX' "$TMP/abi/match.conf"; then
    expect_out 'CXXABI_1.3.0' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/cxxabi.conf"
  else
    printf 'TARGET_CXXABI_MAX=GLIBCXX_9.9.9 CXXABI_1.3.0\n' >> "$TMP/abi/cxxabi.conf"
    expect_out 'CXXABI' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/cxxabi.conf"
  fi

  it "an unstated ABI namespace is reported as unchecked, not passed over"
  # A ceiling naming only one namespace must not look like both were verified.
  sed 's/^TARGET_CXXABI_MAX=.*/TARGET_CXXABI_MAX=GLIBCXX_9.9.9/' \
      "$TMP/abi/match.conf" > "$TMP/abi/onens.conf"
  grep -q 'TARGET_CXXABI_MAX' "$TMP/abi/onens.conf" \
    || printf 'TARGET_CXXABI_MAX=GLIBCXX_9.9.9\n' >> "$TMP/abi/onens.conf"
  expect_out 'NOT checked' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/onens.conf"

  it "an arch MISSING from the table warns instead of silently passing"
  # Regression: an arch absent from the verifier's table produced
  # "-- architecture: no expectation" and PASSED — so an x86-64 binary verified clean
  # against a target it could never run on. The check must fail OPEN LOUDLY, not quietly.
  sed 's/^TARGET_ARCH=.*/TARGET_ARCH=vax/' "$TMP/abi/match.conf" > "$TMP/abi/unk.conf"
  expect_out 'cannot check' "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/unk.conf"

  it "--strict rejects an unverifiable architecture"
  expect_fail "$ROOT/tools/verify-artifact.sh" "$TMP/abi/app" --target-conf "$TMP/abi/unk.conf" --strict

it "the arch table is the single source for cpu-flag, elf-machine and deb-arch"
# Claim-1 guard: an independent review found the arch knowledge duplicated in
# mk/derive.mk and tools/verify-artifact.sh, so adding an ARCHITECTURE meant editing
# two engine files — and the verifier's copy failed open. Both now read this table.
if [[ $("$ROOT/tools/arch-table.sh" cpu-flag aarch64) == mcpu ]] \
