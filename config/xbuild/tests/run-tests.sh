# The two scanners below search the tree for constructs that must not come back. Their own
# patterns necessarily CONTAIN those constructs, so every line belonging to a scanner is
# tagged and filtered out; without that they match themselves and fail forever. The tag is
# checked for, not assumed: a scanner whose tag is lost would silently stop scanning.
PORTABILITY_SCAN_TAG='portability-scanner'

# The patterns live on single tagged lines. grep reports the line a match is ON, so the tag
# has to share that line — with it on a continuation line the scanners matched their own
# source and failed permanently, which is the same "test reports itself" trap as a fixture
# that only works on the author's machine.
P_BASH4='\$\{[A-Za-z_][A-Za-z0-9_]*:[0-9]+:-[0-9]+\}|declare -A|local -A|mapfile |readarray '   # portability-scanner
P_GNU="paste -sd[^ -]+[[:space:]]*\$|touch -d |xargs -r|-printf|grep -P|stat -c|date -d "        # portability-scanner
P_BRE='sed [^|]*\\\?|sed [^|]*\\\||sed -i '                                                     # portability-scanner
P_BAIT='v=${x:1:-1}'                                                                            # portability-scanner
P_BAIT2='declare -A m'                                                                          # portability-scanner
P_BAIT3='touch -d "-1 hour" f'                                                                  # portability-scanner
P_BAIT4='out=$(sed -n "s/^A_\(B_\)\?C=//p" f)'                                                   # portability-scanner
scan() { grep -rnE "$1" "${@:2}" 2>/dev/null | grep -v "$PORTABILITY_SCAN_TAG" | grep -vE ':[0-9]+:[[:space:]]*(#|@#)'; }

it "no bash-4-only construct is reintroduced into the engine"
# macOS ships bash 3.2.57 as /bin/bash and every script here is '#!/usr/bin/env bash', so
# a bash-4 feature is not a portability nicety — it is a runtime failure on a whole class
# of developer machine, and the two that were present failed silently:
#   a negative substring length (bash 4.2) truncated every description
#   an associative-array declaration (bash 4.0) broke every single make invocation
