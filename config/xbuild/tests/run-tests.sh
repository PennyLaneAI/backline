    # this test would pass whether or not the marker is a prerequisite at all — which is
    # exactly how the first version of this test managed to be vacuous.
    make_old "$_tc" "$ROOT/targets/t-stamp.conf"
    # Marker to now (not the future — GNU Make warns about that), so it is the ONLY
    # prerequisite newer than the generated file.
    touch "$_mark"
    make -C "$ROOT" -f "$ROOT/mk/component.mk" ROOT_DIR="$ROOT" TARGET=t-stamp \
         COMPONENT=test-cmake-demo "$_tc" >"$TMP/out" 2>&1
    if [[ -e $_tc && $_tc -nt "$ROOT/targets/t-stamp.conf" ]]; then pass
    else fail "the toolchain file was not regenerated after the sysroot was re-fetched"; fi
    rm -f "$ROOT/targets/t-stamp.conf"
    rm -rf "$ROOT/build/t-stamp" "$ROOT/build/sysroots/t-stamp"

    it "the cmake path gets the SAME std and sysroot flags as the direct path"
    # Regression: gen-cmake-toolchain.sh omitted -std=gnu++NN and all the discovered
    # sysroot -isystem/-B/-L flags, so a cmake component compiled against DIFFERENT
    # headers than a directly-compiled one — the very divergence the generated file
    # exists to prevent.
    #
    # Asserted by COMPARING the two paths, not by naming particular flags. The earlier form
    # required the literal strings 'isystem' and 'rpath-link', both of which are correctly
    # ABSENT for a libc++/Mach-O target — clang finds libc++'s headers through the sysroot,
    # and Mach-O has no -rpath-link — so it failed on a Mac for a toolchain file that
    # matched the direct path in every particular. A test that encodes one platform's flag
    # names cannot check the property it is named after.
    tc="$ROOT/build/$T/toolchain.cmake"
    # ONLY the two flag lines. Scanning all of show-target's output also picked up the
    # build directory and the deploy directory, which are reported there but are not flags
    # and have no business in a toolchain file.
    _shown=$(make -C "$ROOT" --no-print-directory show-target TARGET=$T 2>/dev/null \
             | sed -n -e 's/^  compile: //p' -e 's/^  link:    //p')
    _std=$(printf '%s\n' "$_shown" | sed -n 's/.*\(-std=gnu++[0-9a-z]*\).*/\1/p' | head -1)
    # Every absolute path the direct path passes, however it was spelled: -isystem takes its
    # path as a separate word, -B/-L/--sysroot=/-Wl,-rpath-link, attach theirs. Stripping the
    # prefixes and keeping what starts with '/' covers all of them without pairing words.
    _want_paths=$(printf '%s\n' $_shown \
                  | sed -e 's|^-isystem$||' -e 's|^-[BLI]||' \
                        -e 's|^--sysroot=||' -e 's|^-Wl,-rpath-link,||' \
                  | grep '^/' | sort -u)
    _missing=""
    [[ -n $_std ]] && ! grep -qF -- "$_std" "$tc" && _missing="$_missing $_std"
    while read -r pth; do
      [[ -z $pth ]] && continue
      grep -qF -- "$pth" "$tc" || _missing="$_missing $pth"
    done <<< "$_want_paths"
    if [[ -n $_std && -z $_missing ]]; then pass
    else fail "the generated toolchain file does not carry what the direct path uses. std='$_std' missing:$_missing"; fi
  fi
