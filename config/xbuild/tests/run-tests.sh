      # all about one run in five: the artifact had just been built, `touch` put the
      # toolchain file in the same second, and Make — which also compares whole seconds and
      # treats equal as up to date — decided there was nothing to do. The reconfigure check
      # lives inside that recipe, so it never ran and the cache kept its aged stamp.
      make_old "$_cache" "$_ref" "$ROOT/build/$T/components/test-cmake-demo/cmake-demo"
      touch "$ROOT/build/$T/toolchain.cmake"
      make -C "$ROOT" build TARGET=$T COMPONENT=test-cmake-demo >"$TMP/out" 2>&1
      if [[ -e $_cache ]] && [[ $_cache -nt $_ref ]]; then pass
      else fail "the cmake cache was reused despite a newer toolchain file (INIT flags would be ignored)"; fi
