   && [[ $("$ROOT/tools/arch-table.sh" elf-machine s390x) == "IBM S/390" ]] \
   && [[ -z $("$ROOT/tools/arch-table.sh" elf-machine vax) ]]; then pass
else fail "the arch table returned an unexpected value (field parsing?)"; fi

it "no engine file keeps its own private arch list"
# Greps for the pattern of a re-introduced duplicate table.
