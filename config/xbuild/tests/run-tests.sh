it "a description asking for C++17 is RAISED to C++20, not obeyed"
# Regression, twice over: Catalyst's headers use C++20 concepts, and compiling them as
# C++17 fails with "unknown type name 'concept'" inside a vendor header. The value was
# hand-fixed in the description and then reset to 17 by the next `make probe`, because a
# machine probe writes the whole file and cannot know what standard the SOURCE needs.
