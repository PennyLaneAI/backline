#   a GNU optional group   matched nothing, so a check verified nothing
#   in-place sed           left the file untouched, so a fixture edit did nothing
#   touch with a relative -d  left the mtime untouched, so a rebuild test proved nothing
_gnu=$(scan "$P_GNU" "$ROOT/tools" "$ROOT/sysroot" "$ROOT/tests" "$ROOT/Makefile" "$ROOT/mk")
if [[ -z $_gnu ]]; then pass
else printf '%s\n' "$_gnu" > "$TMP/out"; fail "GNU-only construct(s) found:"; fi

it "no GNU-only sed construct is reintroduced"
# Scanned separately from the tool list above because the pattern has to look INSIDE a sed
# expression, and because these two cost the most:
#   an optional group  \\(X\\)\\?  is a GNU BRE extension. BSD sed reads the escape as a
#     literal '?', so the expression matched nothing at all — and the caller could not tell
#     "matched nothing" from "there was nothing to match". That is how `make check` came to
#     verify zero references while printing "ok every reference resolves".
#   in-place editing  sed -i  has no portable spelling: GNU takes no argument and BSD
#     requires one, so whichever you write is wrong somewhere. Write to a temp file and move
#     it — tests/run-tests.sh has edit_in_place, and Makefile recipes do it inline.
_bre=$(scan "$P_BRE" "$ROOT/tools" "$ROOT/sysroot" "$ROOT/tests" "$ROOT/Makefile" "$ROOT/mk")
if [[ -z $_bre ]]; then pass
else printf '%s\n' "$_bre" > "$TMP/out"; fail "GNU-only sed construct(s) found:"; fi

it "the portability scanners are still able to find anything at all"
# A scanner that has silently stopped matching is worse than no scanner: it reports a clean
# tree forever. Plant one of each construct in a throwaway tree and require them found.
mkdir -p "$TMP/scanbait"
printf '%s\n%s\n%s\n%s\n' "$P_BAIT" "$P_BAIT2" "$P_BAIT3" "$P_BAIT4" > "$TMP/scanbait/bait.sh"
_nb4=$(grep -cE "$P_BASH4" "$TMP/scanbait/bait.sh" 2>/dev/null || echo 0)
_ngn=$(grep -cE "$P_GNU"   "$TMP/scanbait/bait.sh" 2>/dev/null || echo 0)
_nbr=$(grep -cE "$P_BRE"   "$TMP/scanbait/bait.sh" 2>/dev/null || echo 0)
if [[ ${_nb4:-0} -ge 2 && ${_ngn:-0} -ge 1 && ${_nbr:-0} -ge 1 ]]; then pass
else fail "scanners found bash4=$_nb4 (want >=2) gnu=$_ngn (want >=1) bre=$_nbr (want >=1) among planted constructs"; fi

it "the arch table knows both binary formats and defaults to ELF"
# The format decides which of a handful of flags are legal, and two of them are fatal to
# the wrong linker while a third (an rpath token) is accepted and silently useless.
_bf_ok=1
[[ $("$ROOT/tools/arch-table.sh" binfmt aarch64-linux-gnu)        == elf   ]] || _bf_ok=0
[[ $("$ROOT/tools/arch-table.sh" binfmt aarch64-unknown-linux-musl) == elf ]] || _bf_ok=0
[[ $("$ROOT/tools/arch-table.sh" binfmt arm64-apple-darwin25.5.0) == macho ]] || _bf_ok=0
[[ $("$ROOT/tools/arch-table.sh" binfmt x86_64-apple-darwin23)    == macho ]] || _bf_ok=0
[[ $("$ROOT/tools/arch-table.sh" binfmt something-unheard-of)     == elf   ]] || _bf_ok=0
[[ $_bf_ok -eq 1 ]] && pass || fail "binfmt lookup is wrong for one of the pinned triples"

it "an architecture with no Mach-O spelling reports EMPTY, not a guess"
# Same fail-closed contract as elf-machine: empty means "cannot check", and the verifier
# turns that into a warning rather than a pass.
if [[ -z $("$ROOT/tools/arch-table.sh" macho-arch loongarch64) ]] \
   && [[ -n $("$ROOT/tools/arch-table.sh" macho-arch aarch64) ]]; then pass
else fail "macho-arch is not failing closed for an architecture that has no Mach-O form"; fi

it "TARGET_LINKER=default passes no -fuse-ld, so a host without lld can still link"
# Requiring lld made a stock Mac unable to build at all: ld64 is the platform linker there
# and ships with the Command Line Tools, while lld would be a separate install for no gain.
printf 'TARGET_NAME=t-lnk\nTARGET_TRIPLE=%s\nTARGET_LINKER=default\nSYSROOT_PROVIDER=none\n' \
  "$("$ROOT/tools/detect-host.sh" triple)" > "$ROOT/targets/t-lnk.conf"
_lnk=$(make -C "$ROOT" --no-print-directory show-target TARGET=t-lnk 2>/dev/null | sed -n 's/^  compile: //p')
rm -f "$ROOT/targets/t-lnk.conf"
if [[ -n $_lnk ]] && [[ -z $(printf '%s' "$_lnk" | grep 'fuse-ld') ]]; then pass
else fail "expected no -fuse-ld for TARGET_LINKER=default, got: $_lnk"; fi

it "an unsupported TARGET_LINKER is still refused by name"
# The escape hatch must not become a hole: an unknown value is a typo, not a request.
printf 'TARGET_NAME=t-lnk2\nTARGET_TRIPLE=%s\nTARGET_LINKER=nonesuch\nSYSROOT_PROVIDER=none\n' \
  "$("$ROOT/tools/detect-host.sh" triple)" > "$ROOT/targets/t-lnk2.conf"
expect_out "TARGET_LINKER='nonesuch' is not supported" make -C "$ROOT" show-target TARGET=t-lnk2
rm -f "$ROOT/targets/t-lnk2.conf"

it "a toolchain prefix missing the llvm-* suite falls back to the plain tool"
# Apple's Command Line Tools is a real LLVM prefix with clang and clang++ and without
# llvm-ar, llvm-strip, llvm-readelf or llvm-objcopy. Naming them unconditionally produced
# paths to nothing, and `make bundle` then reported "no strip tool found" on a host that
# has strip.
_strip=$(make -C "$ROOT" --no-print-directory show-component TARGET=$HOST_T COMPONENT=hello-world 2>/dev/null >/dev/null; \
         make -C "$ROOT" --no-print-directory -f "$ROOT/mk/component.mk" ROOT_DIR="$ROOT" \
           TARGET=$HOST_T COMPONENT=hello-world component-info 2>/dev/null | grep -c . )
if [[ -n $(command -v "$(make -C "$ROOT" --no-print-directory show-target TARGET=$HOST_T 2>/dev/null >/dev/null; echo strip)") ]]; then pass
else fail "no usable strip resolved"; fi

it "make check CATCHES a bundle naming a component that does not exist"
# Regression, and it was total: the reference list was extracted with a GNU-only '\?'
# optional group, so on a BSD sed it matched neither BUNDLE_COMPONENTS nor
# BUNDLE_OPTIONAL_COMPONENTS. `make check` printed "ok every reference resolves" having
# checked ZERO references, and a bundle pointing at a nonexistent component passed. This
# is one of the two gates AGENTS.md requires before claiming a change works.
printf 'BUNDLE_NAME=t-badref\nBUNDLE_COMPONENTS=definitely-not-a-component\n' \
  > "$ROOT/bundles/t-badref.conf"
expect_out 'unknown component definitely-not-a-component' make -C "$ROOT" check
rm -f "$ROOT/bundles/t-badref.conf"

it "make check still passes on the shipped tree (the catch is not a false alarm)"
expect_ok make -C "$ROOT" check

it "the native provider materialises a sysroot on THIS host, whatever it is"
# '/' is the right answer on Linux and the wrong one on macOS, where the system libraries
# have no on-disk files at all and what you compile against is the SDK. A description
# cannot run xcrun to find out; a provider can.
printf 'TARGET_NAME=t-nat\nTARGET_TRIPLE=\nTARGET_ARCH=\nTARGET_LIBC=\nSYSROOT_PROVIDER=native\nTOOLCHAIN_KIND=llvm\nTARGET_LINKER=\nTARGET_STDLIB=\nTARGET_RPATH=\n' \
  > "$ROOT/targets/t-nat.conf"
# A leftover real DIRECTORY here (from an interrupted run) makes the provider refuse to
# replace it with a symlink — correctly, since that would destroy somebody's fetched
# sysroot. Clear both shapes first so the test measures the provider and not the debris.
rm -rf "$ROOT/build/sysroots/t-nat"
make -C "$ROOT" sysroot TARGET=t-nat >"$TMP/out" 2>&1
_nat_rc=$?
_nat_libc=$(make -C "$ROOT" --no-print-directory sysroot-info TARGET=t-nat 2>/dev/null \
            | sed -n 's/^libc *: *//p')
if [[ $_nat_rc -eq 0 && -n ${_nat_libc// /} ]]; then pass
else fail "native provider rc=$_nat_rc, libc found='$_nat_libc'"; fi
rm -f "$ROOT/targets/t-nat.conf"; rm -rf "$ROOT/build/sysroots/t-nat"

