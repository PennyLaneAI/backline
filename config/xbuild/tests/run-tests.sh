it "the ssh-rsync provider survives rsync's partial-transfer exit codes"
# Regression, and an expensive one: copying a live rootfs as a non-root user always meets a few
# unreadable files (0700 daemon helpers like /usr/lib/cups/backend/*), which rsync reports as
# exit 23 AFTER transferring everything else. Treating that as fatal abandoned a ~6GB fetch that
# had completed, and since the completion marker is only written on success, what remained looked
# like a mysteriously half-populated sysroot — with the real cause long scrolled past.
