# ── the vendor dialect ───────────────────────────────────────────────────────
# The architecture's SPELLING names its vendor: gfx<n> is AMD, sm_<n> is NVIDIA. Every test
# here covers a way the wrong answer is quiet: a flag nvcc rejects only after the useful
# error is gone, a soname silently not recorded, or device code built for the wrong card.

_gpuinfo() {  # _gpuinfo <component> <arch> [extra make vars...]
  _c=$1; _a=$2; shift 2
  make -C "$ROOT" -f "$ROOT/mk/component.mk" ROOT_DIR="$ROOT" TARGET=t-noarch \
    COMPONENT="$_c" CATALYST=/tmp $(test -n "$_a" && echo "GPU_ARCH=$_a") "$@" \
    component-info 2>&1
}

it "an NVIDIA card is described to nvcc in nvcc's own spelling"
# sm_80 has to arrive as '-gencode arch=compute_80,code=sm_80'. The number appears twice and
# a .conf value may hold only a bare $(NAME) reference, so nothing in the description can
# derive the second half — if this breaks, the description silently reverts to AMD's form.
_gpuinfo gpu-coprocessor sm_80 >"$TMP/out"
if grep -q 'gencode arch=compute_80,code=sm_80' "$TMP/out"; then
  grep -q 'offload-arch' "$TMP/out" \
    && fail "emitted the NVIDIA flag but left AMD's --offload-arch beside it" || pass
else
  fail "an sm_ architecture did not produce nvcc's -gencode spelling"
fi

it "nvcc is never handed the GNU spellings it refuses"
# -std=gnu++NN is refused outright ("Value 'gnu++20' is not defined for option 'std'") and is
# the FIRST thing nvcc refuses, which is why the architecture flag looked like the blocker for
# so long. The soname is the dangerous one: hipcc folds '-Wl,a,b' into -Xcompiler and nvcc
# splits it on the commas, and the resulting form is accepted in SILENCE with no SONAME
# recorded — a green build whose artifact cannot be linked against by name.
_gpuinfo gpu-coprocessor sm_80 >"$TMP/out"
if grep -q -- '-std=gnu++' "$TMP/out"; then
  fail "nvcc was handed -std=gnu++, which it refuses outright"
elif ! grep -q -- '-std=c++' "$TMP/out"; then
  fail "the C++ standard reached nvcc in no form at all"
elif grep -q '^soname .*-Wl,-soname' "$TMP/out"; then
  fail "the soname used the -Wl form, which nvcc takes silently and does not record"
elif ! grep -q '^soname .*-Xlinker -soname -Xlinker' "$TMP/out"; then
  fail "the soname reached the linker in neither spelling"
else
  pass
fi

it "an AMD card still gets the spellings that already worked"
