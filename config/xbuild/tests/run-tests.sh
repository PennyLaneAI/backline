#!/usr/bin/env bash
#
# run-tests.sh — the regression suite for the build system itself.
#
# WHY A BUILD SYSTEM NEEDS TESTS
# A build system's bugs do not look like bugs. They look like your code being
# broken. When a build system silently drops a library from a bundle, or silently
# keeps only the first word of a multi-word setting, you go looking in your own
# source for hours. Every test below corresponds to a failure of that shape — most
# of them found by running these very checks during development.
#
# Each test names WHAT it protects and WHY that matters, so a future failure tells
# you what regressed rather than just that something did.
#
# USAGE
#   tests/run-tests.sh            run everything
#   tests/run-tests.sh -v         show output from each test
#
# Requires: a C++ compiler (gcc or clang). Tests needing tools that are absent are
# reported as SKIP rather than failing, so the suite is useful on a partial host.

set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
VERBOSE=0
[[ ${1:-} == -v ]] && VERBOSE=1

PASS=0; FAIL=0; SKIP=0
FAILED_NAMES=()

G=""; R=""; Y=""; N=""
if [[ -t 1 ]]; then G=$'\033[32m'; R=$'\033[31m'; Y=$'\033[33m'; N=$'\033[0m'; fi

TMP=$(mktemp -d "${TMPDIR:-/tmp}/crossbuild-tests-XXXXXX")
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT

# ── harness ──────────────────────────────────────────────────────────────────
# `it` records the intent; `expect_ok` / `expect_fail` assert on a command.
CURRENT=""
it()   { CURRENT=$1; }
why()  { [[ $VERBOSE -eq 1 ]] && printf '        (%s)\n' "$1"; return 0; }

pass() { PASS=$((PASS+1)); printf '  %sPASS%s  %s\n' "$G" "$N" "$CURRENT"; }
fail() {
  FAIL=$((FAIL+1)); FAILED_NAMES+=("$CURRENT")
  printf '  %sFAIL%s  %s\n' "$R" "$N" "$CURRENT"
  [[ -n ${1:-} ]] && printf '        %s\n' "$1"
  if [[ -s $TMP/out ]]; then sed 's/^/        | /' "$TMP/out" | head -20; fi
}
skip() { SKIP=$((SKIP+1)); printf '  %sSKIP%s  %s (%s)\n' "$Y" "$N" "$CURRENT" "${1:-}"; }

expect_ok()   { if "$@" >"$TMP/out" 2>&1; then pass; else fail "expected success, got exit $?"; fi; }
expect_fail() { if "$@" >"$TMP/out" 2>&1; then fail "expected failure, but it succeeded"; else pass; fi; }

# expect_out asserts on the MESSAGE, not on the exit status. Most of the messages
# worth testing are error messages, which by definition accompany a non-zero exit —
# so requiring success here would make it impossible to test the very output that
# matters most. Use expect_out_ok when the command must also succeed.
expect_out()  { # expect_out <pattern> <cmd...>
  local pat=$1; shift
  "$@" >"$TMP/out" 2>&1
  if grep -q "$pat" "$TMP/out"; then pass
  else fail "expected output matching: $pat"; fi
}
expect_out_ok() { # expect_out_ok <pattern> <cmd...>  — must succeed AND match
  local pat=$1; shift
  if "$@" >"$TMP/out" 2>&1 && grep -q "$pat" "$TMP/out"; then pass
  else fail "expected success with output matching: $pat"; fi
}

have() { command -v "$1" >/dev/null 2>&1; }

# ── the fixture target that every build-requiring test uses ───────────────────
#
# It has to describe THIS machine, whatever this machine is. The suite previously built
# against a shipped description that named x86_64-linux-gnu, gcc prefixed with
# 'x86_64-linux-gnu-', the bfd linker and /lib64/ld-linux-x86-64.so.2 — every one of
# which is a property of one particular laptop. On anything else, 22 tests failed for
# that single reason, and they failed by reporting defects all over the build system:
#     FAIL  an executable component builds
#     FAIL  the built binary actually RUNS
#     FAIL  a bundle assembles with all its components
# when the only thing wrong was the fixture. A test suite that can only pass on its
# author's machine reports the machine, not the code.
#
# Every host-specific field is left BLANK, which the schema defines as "ask the host":
# mk/derive.mk fills the triple from the compiler, and the libc, C++ library, rpath token
# and linker from the target's binary format. SYSROOT_PROVIDER=native discovers where
# this machine keeps its headers and libraries, which is '/' on Linux and the SDK on
# macOS. Nothing here names an architecture, an OS or a tool path.
#
# Generated rather than shipped, for the same reason the t-* fixtures are: a test's
# fixture is part of the test, and leaving it in targets/ would offer users a
# description that exists only to be overwritten.
# What this host's compiler produces, asked of the tree's own platform table rather than
# guessed from `uname`. Several groups below are format-specific and need to say so.
HOST_BINFMT=$("$ROOT/tools/arch-table.sh" binfmt "$("$ROOT/tools/detect-host.sh" triple 2>/dev/null)" 2>/dev/null || echo elf)

HOST_T=test-host-native
write_host_fixture() {
  cat > "$ROOT/targets/$HOST_T.conf" <<EOF
# GENERATED by tests/run-tests.sh. Removed when the suite exits.
TARGET_NAME=$HOST_T
TARGET_DESC="This build machine, as the test suite sees it"
TARGET_TRIPLE=
TARGET_ARCH=
TARGET_CPU=
TARGET_LIBC=
TARGET_LIBC_VERSION=
SYSROOT_PROVIDER=native
TOOLCHAIN_KIND=llvm
TARGET_LINKER=
TARGET_STDLIB=
TARGET_CXX_STANDARD=20
TARGET_RPATH=
TARGET_DEPLOY_DIR=/tmp/$HOST_T
EOF
}
write_host_fixture
# Removed on the way out, including on an interrupt, so a failed run does not leave a
# description behind that `make validate` would then report on.
#
# EVERY fixture, not just the host one. This suite writes about twenty throwaway descriptions
# into the real targets/, components/ and bundles/ directories, and only the success path
# removed them — so a run that was interrupted (Ctrl-C, a timeout, a killed terminal) left
# stray descriptions in a SOURCE directory that `make check`, `make build` and
# `make list-components` all read. One of them, zz-dep.conf, is left carrying a deliberate
# dependency CYCLE by the test that follows it. That is the shape of a suite which "fails
# once, then passes with no change in between", and of a working tree that quietly stops
# matching git.
#
# The prefixes are chosen to be unambiguous: real descriptions here are named `test-*` or
# `example-*`, and the glob `t-*` cannot match `test-` (the second character must be a dash).
# Nothing below can remove a file that belongs to the repository.
cleanup() {
  rm -rf "$TMP"
  rm -f "$ROOT/targets/$HOST_T.conf"
  rm -rf "$ROOT/build/sysroots/$HOST_T"
  rm -f "$ROOT"/targets/t-*.conf "$ROOT"/targets/brand-new-box2.conf
  rm -f "$ROOT"/components/t-*.conf "$ROOT"/components/zz-*.conf "$ROOT"/components/aa-user.conf
  rm -f "$ROOT"/bundles/t-*.conf
  rm -rf "$ROOT"/build/*/components/zz-dep "$ROOT"/build/*/components/aa-user
}
trap cleanup EXIT

# ── portable stand-ins for two GNU-only tools ────────────────────────────────
# The suite must run wherever the build system runs, so it may not assume GNU coreutils
# or GNU sed. Both of these were GNU-only and both failed on macOS: one as a missing
# command, one silently.

# `timeout` is GNU coreutils and is absent on macOS (Homebrew installs it as gtimeout).
# Used only to stop a hung test from hanging the whole suite, so a shell watchdog is
# enough. Returns the command's own status, or 124 on timeout as GNU timeout does.
with_timeout() {
  local secs=$1; shift
  if have timeout;  then timeout  "$secs" "$@"; return $?; fi
  if have gtimeout; then gtimeout "$secs" "$@"; return $?; fi
  "$@" & local cmd=$!
  ( sleep "$secs"; kill -0 "$cmd" 2>/dev/null && kill -TERM "$cmd" 2>/dev/null ) & local dog=$!
  local rc=0
  wait "$cmd" 2>/dev/null || rc=$?
  kill -TERM "$dog" 2>/dev/null; wait "$dog" 2>/dev/null || true
  # A TERM'd child reports 143 (128+15); report it as GNU timeout's 124 so the caller
  # cannot confuse "it hung" with "it failed".
  [[ $rc -eq 143 ]] && rc=124
  return $rc
}

# `touch -d '-1 hour'` is a GNU relative-date form. BSD touch has no equivalent (its
# relative form is -A -010000, spelled differently again), so on macOS it failed with
#     touch: out of range or illegal time specification: YYYY-MM-DDThh:mm:SS[.frac][tz]
# leaving the file's mtime untouched. Every test that then asserted "editing this triggers
# a rebuild" was really asserting "make rebuilt something that was already newer", and
# reported the build system as broken.
#
# What those tests actually need is "older than whatever we touch next", not any
# particular age — so use an absolute past timestamp in the POSIX -t form, which both
# implementations accept and which cannot be misread.
make_old() { touch -t 200001010000 "$@"; }

# GNU `sed -i` takes no argument; BSD `sed -i` REQUIRES one. There is no spelling that
# means the same thing to both, and the failure is not loud: on macOS
#     sed -i 's/a/b/' file
# reads 's/a/b/' as the backup suffix and then dies on the file as a script, leaving the
# file untouched. A test whose fixture edit silently did nothing then asserts against the
# ORIGINAL content and reports a defect in the code under test. Write to a temp file and
# move it instead, which behaves identically everywhere.
edit_in_place() {
  local expr=$1 file=$2
  sed "$expr" "$file" > "$file.edited" && mv "$file.edited" "$file"
}

printf '\n═══ crossbuild test suite ═══\n\n'

# ─────────────────────────────────────────────────────────────────────────────
printf 'description validation — a bad description must be REJECTED, not ignored\n'
# Rationale: an ignored typo leaves a default silently in place. You then debug the
# default's behaviour instead of the one-character mistake.
# ─────────────────────────────────────────────────────────────────────────────

it "every shipped description validates"
expect_ok make -C "$ROOT" validate

it "bundle and dependency references all resolve"
expect_ok make -C "$ROOT" check

mkdir -p "$TMP/targets" "$TMP/components"

it "unknown key is rejected (a typo must not be silently ignored)"
printf 'TARGET_NAME=t1\nTARGET_TRIPLE=x86_64-linux-gnu\nTARGET_TRIPPLE=oops\n' > "$TMP/targets/t1.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/targets/t1.conf"

it "shell command substitution in a TARGET is rejected (targets are sourced by shell)"
printf 'TARGET_NAME=t2\nTARGET_TRIPLE=$(id -un)\n' > "$TMP/targets/t2.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/targets/t2.conf"

it "backticks are rejected everywhere"
printf 'TARGET_NAME=t3\nTARGET_TRIPLE=`id`\n' > "$TMP/targets/t3.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/targets/t3.conf"

it "shell constructs are rejected (a description is data, not a program)"
printf 'TARGET_NAME=t4\nif true; then echo hi; fi\n' > "$TMP/targets/t4.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/targets/t4.conf"

it "TARGET_NAME must match the filename (or artifacts land where you are not looking)"
printf 'TARGET_NAME=different\nTARGET_TRIPLE=x86_64-linux-gnu\n' > "$TMP/targets/t5.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/targets/t5.conf"

it "component MAY use \$(VAR) — it is only ever read by Make"
printf 'COMPONENT_NAME=c1\nCOMPONENT_KIND=executable\nCOMPONENT_SOURCES=$(CATALYST)/a.cpp\n' > "$TMP/components/c1.conf"
expect_ok "$ROOT/tools/conf2mk.sh" "$TMP/components/c1.conf"

it "component must NOT use \$(shell ...) — that would execute code at expansion"
printf 'COMPONENT_NAME=c2\nCOMPONENT_KIND=executable\nCOMPONENT_SOURCES=$(shell id)\n' > "$TMP/components/c2.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/components/c2.conf"

it "component must NOT use \$(wildcard ...) even alongside a legitimate reference"
printf 'COMPONENT_NAME=c3\nCOMPONENT_KIND=executable\nCOMPONENT_SOURCES=$(CATALYST)/a.cpp $(wildcard /etc/*)\n' > "$TMP/components/c3.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/components/c3.conf"

# ─────────────────────────────────────────────────────────────────────────────
printf '\nmulti-word values — the silent-truncation class of bug\n'
# Rationale: BUNDLE_COMPONENTS="a b c" sourced raw by shell runs `b` as a command
# and keeps only "a". The bundle then contains one file instead of three and you
# find out on the target. This was a REAL bug caught by this test.
# ─────────────────────────────────────────────────────────────────────────────

it "multi-word value survives the shell view intact"
printf 'BUNDLE_NAME=b1\nBUNDLE_COMPONENTS=alpha beta gamma\n' > "$TMP/b1.conf"
if out=$("$ROOT/tools/conf2mk.sh" --shell "$TMP/b1.conf" 2>&1) \
   && [[ -n $(printf '%s' "$out" | grep "BUNDLE_COMPONENTS='alpha beta gamma'") ]]; then pass
else fail "multi-word value was not single-quoted in the shell view"; fi

it "sourcing the shell view does not execute the second word as a command"
"$ROOT/tools/conf2mk.sh" --shell "$TMP/b1.conf" > "$TMP/b1.sh" 2>/dev/null
if ( set -e; . "$TMP/b1.sh"; [[ $BUNDLE_COMPONENTS == "alpha beta gamma" ]] ) >"$TMP/out" 2>&1; then pass
else fail "sourcing the generated shell view mangled the value"; fi

it "an inline comment does not corrupt a value (it silently disabled the ABI check)"
# Regression: Make strips ' # ...' from a value but shell does not. So
# "TARGET_LIBC=glibc  # confirmed" reached the verifier as the whole string, which took
# the "not glibc" branch and SKIPPED the symbol-version ceiling check — the most
# valuable check in the system, disabled by an annotation.
printf 'TARGET_NAME=b2\nTARGET_LIBC=glibc   # confirmed on the board\n' > "$TMP/b2.conf"
if out=$("$ROOT/tools/conf2mk.sh" --shell "$TMP/b2.conf" 2>&1) \
   && [[ -n $(printf '%s' "$out" | grep "TARGET_LIBC='glibc'") ]]; then pass
else fail "inline comment was not stripped from the shell view"; fi

it "a lone \$ is rejected (\$ORIGIN silently becomes 'RIGIN')"
# Regression: Make expands '$O' to nothing, so TARGET_RPATH=$ORIGIN produced an RPATH
# of literally 'RIGIN' and the verifier reported it as ok.
printf 'TARGET_NAME=b3\nTARGET_TRIPLE=x86_64-linux-gnu\nTARGET_RPATH=$ORIGIN\n' > "$TMP/b3.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/b3.conf"

it "\${shell ...} is rejected in a target (Make treats \${} and \$() identically)"
# Regression: a real code-execution bypass. Only '$(' was checked, so
# 'TARGET_CFLAGS=${shell touch /tmp/X}' passed validation and then executed.
printf 'TARGET_NAME=b4\nTARGET_TRIPLE=x86_64-linux-gnu\nTARGET_CFLAGS=${shell id}\n' > "$TMP/b4.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/b4.conf"

it "an unterminated \$( is rejected"
printf 'COMPONENT_NAME=b5\nCOMPONENT_KIND=executable\nCOMPONENT_SOURCES=$(FOO\n' > "$TMP/b5.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/b5.conf"

it "a duplicated key is rejected (Make takes the first, shell the last)"
# Regression: the two views disagreed, so the compiler and the verifier used different
# values for the same setting with nothing to indicate it.
printf 'TARGET_NAME=b6\nTARGET_TRIPLE=x86_64-linux-gnu\nTARGET_CPU=a\nTARGET_CPU=b\n' > "$TMP/b6.conf"
expect_fail "$ROOT/tools/conf2mk.sh" "$TMP/b6.conf"

# ─────────────────────────────────────────────────────────────────────────────
printf '\nsysroot discovery — must adapt to the layout, not assume one\n'
# Rationale: the original design hardcoded Debian multiarch + a STATIC libc.a +
# GCC 13. A rootfs copied off a real device has no static libs, and any other GCC
# version failed with "vector: file not found" — an error naming neither GCC nor a
# version.
# ─────────────────────────────────────────────────────────────────────────────

# The libstdc++ version used by the fixtures below. Deliberately NOT the version this host
# happens to ship, and named once rather than written into thirty paths: the code under test
# is supposed to DISCOVER whatever version a sysroot contains, so a fixture hardcoding a
# plausible number (14, say) can pass for the wrong reason — by coinciding with the host —
# and would need editing every time the host is upgraded.
_FIXV=41
_FIXV_OLD=40      # an older one, for asserting that the NEWEST present is chosen
_FIXV_STALE=39    # absent on purpose, for asserting that a stale pin fails by name

it "a sysroot with only a SHARED libc is accepted (device rootfs has no libc.a)"
mkdir -p "$TMP/sr-shared/usr/lib/aarch64-linux-gnu"
: > "$TMP/sr-shared/usr/lib/aarch64-linux-gnu/libc.so.6"
expect_ok "$ROOT/tools/sysroot-inspect.sh" probe "$TMP/sr-shared" aarch64-linux-gnu

it "a musl sysroot is accepted (no glibc, no libc.so.6)"
mkdir -p "$TMP/sr-musl/usr/lib"
: > "$TMP/sr-musl/usr/lib/ld-musl-aarch64.so.1"
expect_ok "$ROOT/tools/sysroot-inspect.sh" probe "$TMP/sr-musl" aarch64-linux-musl

it "a non-multiarch (lib64) sysroot is accepted (Fedora/RHEL layout)"
mkdir -p "$TMP/sr-lib64/usr/lib64"
: > "$TMP/sr-lib64/usr/lib64/libc.so.6"
expect_out_ok 'usr/lib64' "$ROOT/tools/sysroot-inspect.sh" libdir "$TMP/sr-lib64" x86_64-linux-gnu

it "a vendor-ful triple still finds a vendorless multiarch sysroot"
# Regression: detect-host.sh reports this host as x86_64-pc-linux-gnu, while every
# Debian/Ubuntu tree names the directory x86_64-linux-gnu — multiarch omits the vendor
# field. Searching only for the spelling we were handed made a perfectly good sysroot
# report "contains no C library", so a native target that leaves TARGET_TRIPLE blank (the
# documented way to write one) could not build at all without a command-line override.
mkdir -p "$TMP/sr-vendor/usr/lib/x86_64-linux-gnu"
: > "$TMP/sr-vendor/usr/lib/x86_64-linux-gnu/libc.so.6"
expect_out_ok 'usr/lib/x86_64-linux-gnu' \
  "$ROOT/tools/sysroot-inspect.sh" libdir "$TMP/sr-vendor" x86_64-pc-linux-gnu

it "the exact triple still WINS over the vendorless fallback"
# The fallback must be strictly ADDITIVE. With both spellings present, the one the
# description asked for is the answer — otherwise this would silently redirect existing
# builds to a different directory, which is a worse bug than the one being fixed.
mkdir -p "$TMP/sr-both/usr/lib/x86_64-pc-linux-gnu" "$TMP/sr-both/usr/lib/x86_64-linux-gnu"
: > "$TMP/sr-both/usr/lib/x86_64-pc-linux-gnu/libc.so.6"
: > "$TMP/sr-both/usr/lib/x86_64-linux-gnu/libc.so.6"
expect_out_ok 'usr/lib/x86_64-pc-linux-gnu' \
  "$ROOT/tools/sysroot-inspect.sh" libdir "$TMP/sr-both" x86_64-pc-linux-gnu

it "derived cxxflags are IDENTICAL for both spellings of one machine"
# The quiet half of the same bug: these paths are all [[ -d ]] guarded, so a vendor
# mismatch dropped -isystem and -B with no error at all — surfacing much later as a
# missing bits/c++config.h, or a crtbegin.o taken from the host's wrong architecture.
mkdir -p "$TMP/sr-flags/usr/lib/x86_64-linux-gnu" \
         "$TMP/sr-flags/usr/include/c++/$_FIXV/"{bits,debug} \
         "$TMP/sr-flags/usr/include/x86_64-linux-gnu/c++/$_FIXV/bits" \
         "$TMP/sr-flags/usr/lib/gcc/x86_64-linux-gnu/$_FIXV"
: > "$TMP/sr-flags/usr/lib/x86_64-linux-gnu/libc.so.6"
: > "$TMP/sr-flags/usr/include/c++/$_FIXV/debug/assertions.h"
: > "$TMP/sr-flags/usr/include/x86_64-linux-gnu/c++/$_FIXV/bits/c++config.h"
# The support directory has to contain a crtbegin, because that object is what identifies
# it. The two layouts a real sysroot uses — usr/lib/gcc/<triple>/<ver> on Debian and
# usr/lib/<vendor-triple>/<ver> on an OpenEmbedded SDK — cannot be told apart by shape
# alone, and the second is indistinguishable from the multiarch library directory next to
# it. An empty directory here made the fixture describe a sysroot that cannot exist.
: > "$TMP/sr-flags/usr/lib/gcc/x86_64-linux-gnu/$_FIXV/crtbegin.o"
_fl_vendor=$("$ROOT/tools/sysroot-inspect.sh" cxxflags "$TMP/sr-flags" x86_64-pc-linux-gnu libstdc++)
_fl_plain=$( "$ROOT/tools/sysroot-inspect.sh" cxxflags "$TMP/sr-flags" x86_64-linux-gnu    libstdc++)
if [[ $_fl_vendor == "$_fl_plain" ]] \
   && [[ $_fl_vendor == *"isystem $TMP/sr-flags/usr/include/x86_64-linux-gnu/c++/$_FIXV"* ]] \
   && [[ $_fl_vendor == *"-B$TMP/sr-flags/usr/lib/gcc/x86_64-linux-gnu/$_FIXV"* ]]; then pass
else fail "flags differ between two spellings of one machine:
  vendor-ful : $_fl_vendor
  vendorless : $_fl_plain"; fi

it "a musl triple is not mangled by the vendorless fallback"
# The vendor list must not eat a field that is not a vendor: 'aarch64-linux-musl' has no
# vendor at all, and losing 'musl' would point a musl target at a glibc directory.
if out=$("$ROOT/tools/detect-host.sh" multiarch-triple aarch64-linux-musl 2>&1) \
   && [[ $out == aarch64-linux-musl ]]; then pass
else fail "expected aarch64-linux-musl unchanged, got '${out:-}'"; fi

it "a sysroot whose lib/ is a SYMLINK still resolves (merged-/usr)"
# The providers now reproduce a symlinked /lib rather than following it, which is how a stock
# merged-/usr target stops being copied twice. Everything downstream has to cope with the
# resulting shape.
mkdir -p "$TMP/sr-merged/usr/lib/x86_64-linux-gnu"
: > "$TMP/sr-merged/usr/lib/x86_64-linux-gnu/libc.so.6"
: > "$TMP/sr-merged/usr/lib/x86_64-linux-gnu/libfoo.so"
ln -sfn usr/lib "$TMP/sr-merged/lib"
expect_out_ok 'usr/lib/x86_64-linux-gnu' \
  "$ROOT/tools/sysroot-inspect.sh" libdir "$TMP/sr-merged" x86_64-linux-gnu

it "haslib says yes for a library the sysroot can link"
expect_ok "$ROOT/tools/sysroot-inspect.sh" haslib "$TMP/sr-merged" x86_64-linux-gnu foo

it "haslib says no, by name, for a library that is absent"
# Regression: a component declaring COMPONENT_LIBS=ibverbs against a target without
# libibverbs-dev failed with seven copies of "fatal error: 'infiniband/verbs.h' file not
# found" pointing inside a vendor header — naming neither the library, the sysroot, nor the
# target.
expect_out 'not found in the sysroot' \
  "$ROOT/tools/sysroot-inspect.sh" haslib "$TMP/sr-merged" x86_64-linux-gnu ibverbs

it "haslib distinguishes 'no such library' from 'no development package'"
# Different causes, different fixes: one needs the library installed, the other needs the
# -dev package that ships the lib<name>.so linker name.
: > "$TMP/sr-merged/usr/lib/x86_64-linux-gnu/libz.so.1"
expect_out 'only as a runtime library' \
  "$ROOT/tools/sysroot-inspect.sh" haslib "$TMP/sr-merged" x86_64-linux-gnu z

it "haslib accepts a library that exists only as a static archive"
# Since glibc 2.34, libpthread.so/libdl.so/librt.so are gone — their code moved into libc —
# but the '.a' stubs remain and '-lpthread' still resolves. A check that demanded a '.so'
# would refuse every modern glibc target.
: > "$TMP/sr-merged/usr/lib/x86_64-linux-gnu/libpthread.a"
expect_ok "$ROOT/tools/sysroot-inspect.sh" haslib "$TMP/sr-merged" x86_64-linux-gnu pthread

it "an INCOMPLETE C++ header tree is rejected, naming the real cause"
# Regression, reported from the field: the shipped ssh-rsync provider's default
# excludes contained the unanchored pattern 'debug/', which rsync matches at ANY depth.
# It therefore deleted /usr/include/c++/<ver>/debug from the sysroot, and every C++
# compile died with
#     fatal error: 'debug/assertions.h' file not found
# pointing INSIDE libstdc++ (bits/stl_iterator_base_funcs.h), so it read as a broken
# toolchain rather than an incomplete copy. The provider is fixed (anchored patterns);
# this check exists so a sysroot broken by any other means still says so plainly.
mkdir -p "$TMP/sr-nodebug/usr/lib/x86_64-linux-gnu" \
         "$TMP/sr-nodebug/usr/include/c++/$_FIXV/bits"
: > "$TMP/sr-nodebug/usr/lib/x86_64-linux-gnu/libc.so.6"
: > "$TMP/sr-nodebug/usr/include/c++/$_FIXV/bits/stl_iterator_base_funcs.h"
: > "$TMP/sr-nodebug/usr/include/c++/$_FIXV/bits/c++config.h"
# note: no debug/assertions.h — exactly what the unanchored exclude produced
expect_out 'INCOMPLETE' "$ROOT/tools/sysroot-inspect.sh" probe "$TMP/sr-nodebug" x86_64-linux-gnu

it "a COMPLETE C++ header tree passes (no false positive)"
mkdir -p "$TMP/sr-ok/usr/lib/x86_64-linux-gnu" \
