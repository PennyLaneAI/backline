it "a built artifact's RPATH is \$ORIGIN, not 'RIGIN'"
# Regression, and a nasty one: conf2mk emits every setting with '?=' so a command line can
# override it. An environment variable outranks '?=', and Make treats an inherited
# environment value as recursively expanded — so exporting TARGET_RPATH from the top-level
# Makefile sent '$ORIGIN' into the component sub-make, where it expanded a second time and
# '$O' (unset) left an RPATH of literally 'RIGIN'. Descriptions are already checked for this
# shape; this checks the artifact, because the same wrong value can arrive via the
# environment instead of the file.
# The token compared against comes from the artifact's FORMAT, not from a literal: the
# ELF spelling is $ORIGIN and the Mach-O spelling is @loader_path, and asserting the ELF
# one everywhere would fail on a Mach-O host for being correct. The mangling this guards
# against is specific to the '$' doubling, so it can only afflict the ELF token — but the
# check is still worth running on both, because "the token survived into the binary" is
# the property, and on Mach-O a wrong token is accepted silently by the linker.
_rp_fmt=$("$ROOT/tools/arch-table.sh" binfmt "$("$ROOT/tools/detect-host.sh" triple)")
if [[ $_rp_fmt == macho ]]; then _want_rp='@loader_path'; else _want_rp='$ORIGIN'; fi
if { [[ $_rp_fmt == macho ]] && have otool; } || have readelf || have llvm-readelf; then
  make -C "$ROOT" build TARGET=$HOST_T COMPONENT=test-greet-app >/dev/null 2>&1
  _art="$ROOT/build/$HOST_T/components/test-greet-app/greet-app"
  if [[ $_rp_fmt == macho ]]; then
    _rp=$(otool -l "$_art" 2>/dev/null \
          | awk '/^ *cmd LC_RPATH/{f=1;next} f&&/^ *path /{sub(/^ *path /,"");sub(/ \(offset [0-9]+\)$/,"");print;exit}')
  else
    _rp=$(readelf -d "$_art" 2>/dev/null \
          | sed -n -e 's/.*RPATH.*\[\(.*\)\]/\1/p' -e 's/.*RUNPATH.*\[\(.*\)\]/\1/p' | head -1)
  fi
  if [[ $_rp == "$_want_rp" ]]; then pass
  else fail "expected an rpath of $_want_rp, got '${_rp:-<none>}'"; fi
else
  skip "no reader for $_rp_fmt artifacts"
fi

